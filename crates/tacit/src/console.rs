//! Framebuffer text console.  The display is a shaped region of pixels
//! (rank-3: height x width x 4 channels), and the console is a text grid
//! rendered into it with an 8x8 bitmap font.  Writes go straight to RAM with
//! no cache in the way, so QEMU's ramfb sees them immediately.

pub const FB_WIDTH: u32 = 1280;
pub const FB_HEIGHT: u32 = 720;
pub const FB_STRIDE: u32 = FB_WIDTH * 4; // XRGB8888
pub const FB_BYTES: usize = (FB_WIDTH * FB_HEIGHT * 4) as usize;

pub const FONT_W: u32 = 8;
pub const FONT_H: u32 = 8;
pub const COLS: u32 = FB_WIDTH / FONT_W; // 160
pub const ROWS: u32 = FB_HEIGHT / FONT_H; // 90

pub struct Console {
    pub fb: usize,
    row: u32,
    col: u32,
}

