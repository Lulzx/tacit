impl Console {
    pub fn new(fb: usize) -> Self {
        Console { fb, row: 0, col: 0 }
    }

    #[inline]
    fn put_pixel(&self, x: u32, y: u32, c: u32) {
        unsafe {
            let p = (self.fb + (y * FB_STRIDE + x * 4) as usize) as *mut u32;
            core::ptr::write_volatile(p, c);
        }
    }

    pub fn clear(&mut self) {
        for y in 0..FB_HEIGHT {
            for x in 0..FB_WIDTH {
                self.put_pixel(x, y, 0x000000);
            }
        }
        self.row = 0;
        self.col = 0;
    }

    fn scroll(&mut self) {
        // Shift all rows up by one text line, clear the last line.
        let line = (FONT_H * FB_STRIDE) as usize;
        let total = (FB_HEIGHT * FB_STRIDE) as usize;
        unsafe {
            let fb = self.fb as *mut u8;
            let src = self.fb + line;
            core::ptr::copy(src as *const u8, fb, total - line);
            // clear last line
            let last = self.fb + (FB_HEIGHT - FONT_H) as usize * FB_STRIDE as usize;
            for i in 0..(FONT_H * FB_STRIDE) as usize {
                core::ptr::write_volatile((last + i) as *mut u8, 0);
            }
        }
        self.row = ROWS - 1;
    }

    fn newline(&mut self) {
        self.col = 0;
        self.row += 1;
        if self.row >= ROWS {
            self.scroll();
        }
    }

    pub fn put_char(&mut self, ch: char) {
        match ch {
            '\n' => self.newline(),
            '\r' => self.col = 0,
            '\x08' => {
                if self.col > 0 {
                    self.col -= 1;
                }
            }
            c => {
                if self.col >= COLS {
                    self.newline();
                }
                let idx = if (c as u32) >= 0x20 && (c as u32) <= 0x7f {
                    (c as u32 - 0x20) as usize
                } else {
                    0
                };
                let glyph = &FONT[idx];
                let px = self.col * FONT_W;
                let py = self.row * FONT_H;
                for (gy, row_bits) in glyph.iter().enumerate() {
                    for gx in 0..8 {
                        if row_bits & (0x80 >> gx) != 0 {
                            self.put_pixel(px + gx, py + gy as u32, 0xFFFFFF);
                        }
                    }
                }
                self.col += 1;
                if self.col >= COLS {
                    self.newline();
                }
            }
        }
    }

    pub fn write_str(&mut self, s: &str) {
        for ch in s.chars() {
            self.put_char(ch);
        }
    }

    pub fn write_bytes(&mut self, s: &[u8]) {
        for &b in s {
            self.put_char(b as char);
        }
    }

    /// A monotonically increasing measure of how much text has been emitted.
    pub fn char_count(&self) -> usize {
        (self.row * COLS + self.col) as usize
    }

    /// Flush the framebuffer so a coherent (DMA-reading) device sees it.
    pub fn flush(&self) {
        crate::mmu::flush_dcache(self.fb, FB_BYTES);
    }
}
